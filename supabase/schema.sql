create or replace function public.get_or_create_conversation(p_other_user uuid)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_one uuid;
  v_two uuid;
  v_id uuid;
begin
  if auth.uid() is null or auth.uid() = p_other_user then raise exception 'Invalid conversation participants'; end if;
  if not exists (select 1 from public.profiles where id = p_other_user) then raise exception 'User not found'; end if;
  v_one := least(auth.uid(), p_other_user);
  v_two := greatest(auth.uid(), p_other_user);
  insert into public.conversations (participant_one, participant_two)
  values (v_one, v_two)
  on conflict (participant_one, participant_two) do update set last_message_at = public.conversations.last_message_at
  returning id into v_id;
  return v_id;
end;
$$;

