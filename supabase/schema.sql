drop function if exists public.apply_price_listing(text, text, text, text, text, numeric, text, uuid, text, text);

create function public.apply_price_listing(
  p_item text,
  p_country text,
  p_city text,
  p_market text,
  p_unit text,
  p_price numeric,
  p_currency text,
  p_seller_id uuid,
  p_photo_url text,
  p_source text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id bigint;
begin
  perform pg_advisory_xact_lock(hashtext(lower(trim(p_item) || '|' || trim(p_market) || '|' || trim(p_unit) || '|' || trim(p_currency))));
  select id into v_id
  from public.prices
  where lower(trim(item)) = lower(trim(p_item))
    and lower(trim(market)) = lower(trim(p_market))
    and lower(trim(coalesce(unit, ''))) = lower(trim(p_unit))
    and upper(currency) = upper(p_currency)
  order by created_at desc
  limit 1
  for update;

  if v_id is null then
    insert into public.prices (item, country, city, market, unit, price, currency, seller_id, photo_url, source, report_count, verified_count)
    values (trim(p_item), trim(p_country), trim(p_city), trim(p_market), trim(p_unit), p_price, upper(p_currency), p_seller_id, p_photo_url, p_source, 1, 0)
    returning id into v_id;
  else
    update public.prices
    set country = trim(p_country),
        city = trim(p_city),
        price = p_price,
        seller_id = coalesce(p_seller_id, seller_id),
        photo_url = coalesce(p_photo_url, photo_url),
        source = p_source,
        report_count = coalesce(report_count, 0) + 1,
        created_at = now()
    where id = v_id;
  end if;

  insert into public.price_history (price_id, price, currency)
  values (v_id, p_price, upper(p_currency));
  return v_id;
end;
$$;

create or replace function public.auto_review_seller_post()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_average numeric;
begin
  select avg(price) into v_average
  from public.prices
  where lower(trim(item)) = lower(trim(new.item))
    and upper(currency) = upper(new.currency)
    and price > 0;

  if v_average is not null and abs(new.price - v_average) <= v_average * 0.20 then
    perform public.apply_price_listing(new.item, new.country, new.city, new.market, new.unit, new.price, new.currency, new.seller_id, new.photo_url, 'seller-approved');
    update public.seller_posts set status = 'approved', reviewed_at = now() where id = new.id;
  else
    insert into public.pending_reviews (submission_type, submission_id)
    values ('seller_post', new.id::text)
    on conflict (submission_type, submission_id) do nothing;
  end if;
  return new;
end;
$$;

