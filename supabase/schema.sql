create or replace function public.verify_price(p_price_id bigint)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_seller uuid;
  v_count integer;
begin
  if auth.uid() is null then raise exception 'Sign in required'; end if;
  select seller_id into v_seller from public.prices where id = p_price_id;
  if not found then raise exception 'Price not found'; end if;
  if v_seller = auth.uid() then raise exception 'You cannot verify your own price'; end if;
  insert into public.price_verifications (price_id, user_id) values (p_price_id, auth.uid()) on conflict do nothing;
  if not found then raise exception 'You already verified this price'; end if;
  select count(*) into v_count from public.price_verifications where price_id = p_price_id;
  update public.prices set verified_count = coalesce(verified_count, 0) + 1 where id = p_price_id;
  if v_seller is not null and v_count % 3 = 0 then
    update public.seller_profiles set trust_score = least(100, trust_score + 10) where id = v_seller;
  end if;
  return v_count;
end;
$$;

create or replace function public.update_call_status(p_call_id uuid, p_status text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_call public.calls%rowtype;
begin
  if p_status not in ('ongoing', 'ended', 'declined', 'missed', 'cancelled') then raise exception 'Invalid call status'; end if;
  select * into v_call from public.calls where id = p_call_id for update;
  if not found or auth.uid() not in (v_call.caller_id, v_call.receiver_id) then raise exception 'Call not found'; end if;
  if p_status = 'ongoing' and (auth.uid() <> v_call.receiver_id or v_call.status <> 'ringing') then raise exception 'Only the recipient can accept a ringing call'; end if;
  if p_status in ('declined', 'missed') and (auth.uid() <> v_call.receiver_id or v_call.status <> 'ringing') then raise exception 'Only the recipient can decline a ringing call'; end if;
  if p_status = 'cancelled' and (auth.uid() <> v_call.caller_id or v_call.status <> 'ringing') then raise exception 'Only the caller can cancel a ringing call'; end if;
  if p_status = 'ended' and (v_call.status <> 'ongoing' or auth.uid() not in (v_call.caller_id, v_call.receiver_id)) then raise exception 'Only an active call can end'; end if;
  update public.calls
  set status = p_status,
      accepted_at = case when p_status = 'ongoing' then now() else accepted_at end,
      ended_at = case when p_status in ('ended', 'declined', 'missed') then now() else ended_at end,
      duration_sec = case when p_status = 'ended' and accepted_at is not null then greatest(0, floor(extract(epoch from (now() - accepted_at)))::integer) else duration_sec end
  where id = p_call_id;
end;
$$;

create or replace function public.add_call_system_message()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_message text;
begin
  if new.status = old.status or new.status not in ('ended', 'declined', 'missed', 'cancelled') then return new; end if;
  v_message := case
    when new.status = 'missed' then '☎ Missed Call'
    when new.status = 'declined' then '☎ Declined Call'
    when new.status = 'cancelled' then '☎ Cancelled Call'
    when new.accepted_at is null then '☎ Cancelled Call'
    else '☎ ' || case when new.call_type = 'video' then 'Video Call' else 'Voice Call' end || ' - ' || floor(new.duration_sec / 60)::text || ' mins'
  end;
  insert into public.messages (conversation_id, sender_id, receiver_id, message, message_type, is_read)
  values (new.conversation_id, new.caller_id, new.receiver_id, v_message, 'system', false);
  return new;
end;
$$;

